#!/usr/bin/env node
// Generate the teaching document and notebook notes from the ADR index.
//
// The index, docs/decisions/README.md, is the only hand-maintained source. This
// script renders it into docs/why-this-shape.md and, with --vault, into one
// notebook note per row. `--check` writes nothing and exits 1 when either output
// is stale, so CI can fail a changed index with an old document.

import { existsSync, lstatSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO = "document-intake";
const INDEX_REL = "docs/decisions/README.md";
const TEACHING_REL = "docs/why-this-shape.md";
const KNOWN_SENSITIVITY = [
  "public",
  "personal",
  "internal",
  "work",
  "confidential",
  "client-restricted",
];
const HEADER = ["ADR", "Problem", "Options", "Decision", "Cost", "Falsification signal", "Undo"];
const ADR_FILE = /^(\d{4})-[a-z0-9-]+\.md$/;
const ADR_LINK = /^(\d{4})-[a-z0-9-]+\.md$/;

const INTRO = `# Why this shape

Generated from \`docs/decisions/README.md\` by \`npm run docs:decisions\`. Do not edit this file; edit the index row and regenerate.

The template is one local-first vertical slice. An uncertain document waits for a person, and every posted value can name its evidence. The sections below give one decision each, followed by the verification limit.

## The seam an adopter changes first

The \`Extractor\` is the first seam, and the one the fixtures exercise. The demo reads one document shape with a template extractor plus an independent identity read; replacing \`Extractor\` with Document Intelligence or an LLM changes that adapter and leaves the pipeline, the gates, and the evidence invariant in place. The seam exists because extraction varies by document source while the decision rules must not.

The trade-off an adopter meets first is coverage. A second document shape costs a new extractor, not a new pipeline, and the fixtures state the shape the contract expects. \`docs/adapters.md\` names what each port must preserve, so a reader can replace one adapter without reading the rest of the tree.`;

const LIMIT = `## Verification limit

\`npm run verify\` compares each posted key with the local record store. It does not prove that a remote system still holds the record.`;

export class SourceError extends Error {}

function splitRow(line) {
  return line
    .trim()
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((cell) => cell.trim());
}

export function parseIndex(text) {
  const lines = text.split("\n");
  const start = lines.findIndex((line) => /^\|\s*ADR\s*\|/.test(line));
  if (start < 0) throw new SourceError(`${INDEX_REL} has no ADR table`);
  const header = splitRow(lines[start]);
  if (header.length !== HEADER.length || header.some((cell, i) => cell !== HEADER[i])) {
    throw new SourceError(`${INDEX_REL} table header must be: ${HEADER.join(" | ")}`);
  }
  const separator = splitRow(lines[start + 1] ?? "");
  if (separator.length !== HEADER.length || separator.some((cell) => !/^:?-+:?$/.test(cell))) {
    throw new SourceError(`${INDEX_REL} table has no separator row`);
  }

  const rows = [];
  const seen = new Set();
  let end = start + 2;
  for (; end < lines.length && lines[end].startsWith("|"); end += 1) {
    const cells = splitRow(lines[end]);
    if (cells.length !== HEADER.length) {
      throw new SourceError(`${INDEX_REL} row ${end + 1} needs ${HEADER.length} cells`);
    }
    const match = /^\[(\d{4})\]\(([^)]+)\)\s+(.+)$/.exec(cells[0]);
    if (!match) throw new SourceError(`${INDEX_REL} row ${end + 1} needs [id](file.md) Title`);
    const [, id, link, title] = match;
    if (!ADR_LINK.test(link) || !link.startsWith(`${id}-`)) {
      throw new SourceError(`${INDEX_REL} row ${end + 1} links an unexpected ADR: ${link}`);
    }
    if (seen.has(link)) throw new SourceError(`${INDEX_REL} has two rows for ${link}`);
    seen.add(link);
    const row = {
      id,
      link,
      title,
      problem: cells[1],
      options: cells[2],
      decision: cells[3],
      cost: cells[4],
      falsifier: cells[5],
      undo: cells[6],
    };
    for (const key of ["problem", "options", "decision", "cost", "falsifier", "undo"]) {
      if (!row[key]) throw new SourceError(`${INDEX_REL} row ${id} has an empty ${key}`);
    }
    if (!row.undo.includes("`")) throw new SourceError(`${INDEX_REL} row ${id} needs a literal undo command`);
    rows.push(row);
  }
  if (rows.length === 0) throw new SourceError(`${INDEX_REL} table has no rows`);
  const stray = lines.findIndex((line, index) => index >= end && line.startsWith("|"));
  if (stray >= 0) throw new SourceError(`${INDEX_REL} has a table row outside the ADR table: line ${stray + 1}`);
  return rows;
}

function adrHeading(text) {
  const match = /^# (.+)$/m.exec(text);
  if (!match) throw new SourceError("ADR has no heading");
  return match[1].trim();
}

function adrDate(text, link) {
  const match = /^\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})\s*$/m.exec(text);
  if (!match) throw new SourceError(`${link} has no **Date:** YYYY-MM-DD line`);
  return match[1];
}

function loadRows(root) {
  const index = join(root, INDEX_REL);
  if (!existsSync(index)) throw new SourceError(`${INDEX_REL} does not exist`);
  const rows = parseIndex(readFileSync(index, "utf8"));

  const directory = join(root, "docs/decisions");
  const files = readdirSync(directory)
    .filter((name) => ADR_FILE.test(name))
    .sort();
  const indexed = new Set(rows.map((row) => row.link));
  for (const file of files) {
    if (!indexed.has(file)) throw new SourceError(`${file} has no row in ${INDEX_REL}`);
  }

  return rows.map((row) => {
    const path = join(directory, row.link);
    if (!existsSync(path) || !statSync(path).isFile()) {
      throw new SourceError(`${INDEX_REL} links a missing ADR: ${row.link}`);
    }
    const text = readFileSync(path, "utf8");
    const expected = `${row.id}: ${row.title}`;
    const heading = adrHeading(text);
    if (heading !== expected) {
      throw new SourceError(`${row.link} heading is "${heading}", index says "${expected}"`);
    }
    return { ...row, slug: row.link.replace(/\.md$/, ""), created: adrDate(text, row.link) };
  });
}

export function renderTeaching(rows) {
  const sections = rows.map(
    (row) => `## ${row.id}: ${row.title}

**Problem:** ${row.problem}

**Options:** ${row.options}

**Decision:** ${row.decision}

**Cost:** ${row.cost}

**Falsification signal:** ${row.falsifier}

**Undo:** ${row.undo}`,
  );
  return `${INTRO}\n\n${sections.join("\n\n")}\n\n${LIMIT}\n`;
}

export function renderNote(row, sensitivity) {
  return `---
title: "${row.id}: ${row.title}"
type: adr
created: ${row.created}
sensitivity: ${sensitivity}
refs:
  - repo:${REPO}
  - adr:${INDEX_REL.replace("README.md", row.link)}
generated: ${INDEX_REL}
---
# ${row.id}: ${row.title}

## Context

**Problem:** ${row.problem}

**Options:** ${row.options}

## Observation

The evidence and the rejected alternative live in \`docs/decisions/${row.link}\`.

## Decision

${row.decision}

## Consequence

**Cost:** ${row.cost}

## Rollback

Falsifier: ${row.falsifier}

Undo: ${row.undo}
`;
}

function generatedLine(text) {
  const match = /^generated:\s*(.+)$/m.exec(text);
  if (!match) return null;
  return match[1].trim().replace(/^["']|["']$/g, "");
}

export function generate(root, options = {}) {
  const sensitivity = options.sensitivity ?? "internal";
  if (!KNOWN_SENSITIVITY.includes(sensitivity)) {
    throw new SourceError(`unknown sensitivity: ${sensitivity}`);
  }
  const vault = options.vault ?? null;
  if (vault) {
    if (!existsSync(vault)) throw new SourceError(`vault is not a directory: ${vault}`);
    if (lstatSync(vault).isSymbolicLink()) throw new SourceError(`vault is a symlink: ${vault}`);
    if (!statSync(vault).isDirectory()) throw new SourceError(`vault is not a directory: ${vault}`);
  }

  const rows = loadRows(root);
  const teachingPath = join(root, TEACHING_REL);
  const teaching = renderTeaching(rows);
  const teachingStale = !existsSync(teachingPath) || readFileSync(teachingPath, "utf8") !== teaching;

  const notes = vault
    ? rows.map((row) => ({
        path: join(vault, `adr-${row.slug}.md`),
        text: renderNote(row, sensitivity),
      }))
    : [];
  for (const note of notes) {
    if (!existsSync(note.path)) continue;
    if (lstatSync(note.path).isSymbolicLink()) {
      throw new SourceError(`${note.path} is a symlinked note; refusing to overwrite`);
    }
    const source = generatedLine(readFileSync(note.path, "utf8"));
    if (source !== INDEX_REL) {
      throw new SourceError(`${note.path} was not generated from ${INDEX_REL}; refusing to overwrite`);
    }
  }
  const staleNotes = notes.filter(
    (note) => !existsSync(note.path) || readFileSync(note.path, "utf8") !== note.text,
  );

  if (!options.check) {
    if (teachingStale) writeFileSync(teachingPath, teaching);
    for (const note of staleNotes) writeFileSync(note.path, note.text);
  }
  return {
    ok: !teachingStale && staleNotes.length === 0,
    teachingChanged: teachingStale,
    staleNotes: staleNotes.map((note) => note.path),
  };
}

const USAGE = `usage: decisions.mjs [--check] [--vault DIR] [--sensitivity VALUE]

Renders docs/why-this-shape.md from docs/decisions/README.md.
With --vault, also writes one note per row into DIR.
--check writes nothing and exits 1 when an output is stale.`;

export function parseArgs(argv) {
  const options = { check: false, vault: null, sensitivity: "internal", help: false };
  for (let i = 0; i < argv.length; i += 1) {
    switch (argv[i]) {
      case "--check":
        options.check = true;
        break;
      case "--vault":
        i += 1;
        if (i >= argv.length) throw new SourceError("--vault needs a directory");
        options.vault = resolve(argv[i]);
        break;
      case "--sensitivity":
        i += 1;
        if (i >= argv.length) throw new SourceError("--sensitivity needs a value");
        options.sensitivity = argv[i];
        break;
      case "--help":
      case "-h":
        options.help = true;
        break;
      default:
        throw new SourceError(`unknown argument: ${argv[i]}`);
    }
  }
  return options;
}

export function main(argv, root = resolve(dirname(fileURLToPath(import.meta.url)), "..")) {
  let options;
  try {
    options = parseArgs(argv);
  } catch (error) {
    console.error(`decisions: ${error.message}`);
    return 2;
  }
  if (options.help) {
    console.log(USAGE);
    return 0;
  }
  try {
    const result = generate(root, options);
    if (options.check && !result.ok) {
      if (result.teachingChanged) console.error(`decisions: ${TEACHING_REL} is stale`);
      for (const path of result.staleNotes) console.error(`decisions: ${path} is stale`);
      return 1;
    }
    if (!options.check) {
      if (result.teachingChanged) console.log(`wrote ${TEACHING_REL}`);
      for (const path of result.staleNotes) console.log(`wrote ${path}`);
    }
    return 0;
  } catch (error) {
    console.error(`decisions: ${error.message}`);
    return 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
